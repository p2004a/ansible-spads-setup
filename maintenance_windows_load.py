#!/usr/bin/env python3
"""Prints the weekday load of each region for maintenance_windows.mzn.

Run it on bar-mon, from the repo root:

  ssh bar-mon python3 - < maintenance_windows_load.py > maintenance_windows_load.dzn

Load of a host is its CPU (70%) and network (30%) usage, each as share of
the host's peak, median per hour of the week over the last DAYS days. Load of
a region is the mean over its hosts and weekdays, as % of its peak hour.
"""

import json
import re
import statistics
import time
import urllib.parse
import urllib.request
from collections import defaultdict
from datetime import date, datetime, timezone

VICTORIAMETRICS = "http://victoriametrics.dns.podman:8428"
DAYS = 30
QUERIES = [  # (weight, query)
    (0.7, '1 - avg by (instance) (rate(node_cpu_seconds_total{instance=~"spads-.*", mode="idle"}[30m]))'),
    (0.3, 'sum by (instance) (rate(node_network_transmit_bytes_total{instance=~"spads-.*", device!~"lo|veth.*|podman.*"}[30m]))'),
]


def query_range(query, start, end):
    params = urllib.parse.urlencode({"query": query, "start": start, "end": end, "step": "30m"})
    with urllib.request.urlopen(f"{VICTORIAMETRICS}/api/v1/query_range?{params}") as resp:
        return json.load(resp)["data"]["result"]


def hour_of_week_profile(values):
    """Median per (weekday, hour), as share of the peak."""
    buckets = defaultdict(list)
    for ts, value in values:
        t = datetime.fromtimestamp(ts, timezone.utc)
        buckets[t.weekday(), t.hour].append(float(value))
    medians = {k: statistics.median(v) for k, v in buckets.items()}
    peak = max(medians.values())
    return {k: m / peak for k, m in medians.items()}


end = int(time.time())
start = end - DAYS * 86400

# region -> host -> (weekday, hour) -> load
load = defaultdict(lambda: defaultdict(lambda: defaultdict(float)))
for weight, query in QUERIES:
    for series in query_range(query, start, end):
        host = series["metric"]["instance"].removeprefix("spads-")
        region = re.match(r"[a-z]+", host).group().upper()
        for k, v in hour_of_week_profile(series["values"]).items():
            load[region][host][k] += weight * v

print(f"% Generated by maintenance_windows_load.py on {date.today()} from the last {DAYS} days.")
print("REGION = {" + ", ".join(sorted(load)) + "};")
print("load = array2d(REGION, 0..23, [")
for i, region in enumerate(sorted(load)):
    hosts = load[region].values()
    hourly = [statistics.mean(h[day, hour] for h in hosts for day in range(5)) for hour in range(24)]
    row = ", ".join(str(round(100 * x / max(hourly))) for x in hourly)
    print(f"  {row}{',' if i < len(load) - 1 else ''}  % {region}")
print("]);")
